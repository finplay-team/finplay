// 매도 회고의 보유 구간 극값을 어느 정밀도로 쟀는지 나타내는 열거형 (§FEED-012 결정 4).
package com.finplay.api.feedback.domain;

/**
 * 계약은 {@code docs/api-contracts.md}의 매도 직후 피드백 소절이고 근거는 spec §FEED-012 결정 4다.
 *
 * <p><b>주식·코인 공용 필드다.</b> 주식은 언제나 {@link #MINUTE}이고 {@link #DAILY}는 코인에서만 나온다 —
 * 코인에만 필드를 더하면 프론트가 시장으로 분기해야 하고, <b>그 분기는 한 번 생기면 이후 모든 필드 추가가 같은
 * 질문을 다시 받는다.</b>
 *
 * <p><b>저장 컬럼이 아니라 조회 시 판정하는 값이다</b>({@code PostSellFeedbackStatus}와 같다) — 극값 계산에
 * 실제로 쓴 표본이 무엇이었는지의 결과이므로 어디에도 쓰지 않는다.
 */
public enum HoldHighBasis {

	/** 1분봉 close로 잰 정확한 극값. 주식은 언제나 이 값이고, 코인은 보유 구간이 200분 이내일 때다. */
	MINUTE,

	/**
	 * 일봉 close 표본으로 잰 근사 극값 — <b>코인 전용</b>이다.
	 *
	 * <p>코인 분봉 공급자가 200봉 상한이라 그보다 오래 보유한 구간의 1분봉을 조회 시점에 복원할 수 없다
	 * ({@code 013-candle-interval}). 표본은 <b>매수 시각 이후·매도 시각 이전에 확정된 일봉 close</b>뿐이라
	 * 전부 보유 중 실제로 존재했던 가격이고, <b>결과는 실제 최고가 이하다</b>(하루 한 점만 보므로 그 사이의 더
	 * 높은 종가를 놓친다). 화면이 이 값을 근사로 표시할 수 있게 응답에 싣는다.
	 */
	DAILY
}
